#!/usr/bin/env python3
"""Adapter: research_assets.json -> the existing YouTube editor (edl_v3.py / render3.py). Does not modify the editor.
Usage: youtube_editor.py RESEARCH_ASSETS.json OUT_edl_research.py [--seg SEGID=SECONDS ...]
Writes a module that registers each usable still into edl_v3.IMG / edl_v3.CRED (so edl_v3.img(t0, key, ...) works) and, for --seg placements,
appends img() calls at the given narration times. Video assets are listed in VIDEOS for the editor to use with ('F', ...) bases."""
import sys, json, os, re
a = json.load(open(sys.argv[1])); out = sys.argv[2]; seg = dict(x.split('=') for x in sys.argv[sys.argv.index('--seg') + 1:]) if '--seg' in sys.argv else {}
L = ['"""Generated by media_researcher adapters/youtube_editor.py. Only verified, eligible assets."""', 'import edl_v3', 'RESEARCH = []', '']
for u in a['usable']:
    key = 'R_' + re.sub(r'\W', '', u['asset_id'])
    if u['type'] in ('image', 'screenshot'):
        L.append(f"edl_v3.IMG[{key!r}] = ({u['path']!r}, None, .85)")
        L.append(f"edl_v3.CRED[{key!r}] = {(u['credit'] or '')[:70]!r}")
        L.append(f"RESEARCH.append(dict(key={key!r}, segment_ids={u['segment_ids']!r}, url={u['url']!r}, license={u['license']!r}))")
    else:
        L.append(f"VIDEOS = globals().get('VIDEOS', []); VIDEOS.append(dict(path={u['path']!r}, credit={u['credit']!r}, url={u['url']!r}, ranges={u['suggested_timestamp']!r}))")
for sid, t in seg.items():
    for u in a['usable']:
        if sid in u['segment_ids'] and u['type'] in ('image', 'screenshot'):
            key = 'R_' + re.sub(r'\W', '', u['asset_id'])
            L.append(f"edl_v3.img({float(t)}, {key!r}, [(0.3, 3.0, {(u['credit'] or '')[:40]!r}, 'teal', 'research asset', 'br')])"); break
open(out, 'w').write('\n'.join(L) + '\n'); print('wrote', out, len(a['usable']), 'usable assets')
